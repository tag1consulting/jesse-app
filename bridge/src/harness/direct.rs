// ---- The direct harness -----------------------------------------------------
//
// THE THIRD HARNESS, AND THE FIRST WITH NO CHILD PROCESS. `claude-code` and `codex` are CLIs
// the bridge spawns and reads; this one is the `agent/` crate's turn loop, running inside the
// bridge, reached through the [`InProcessHarness`] seam D4 opened.
//
// WHAT IT IS NOT: a re-implementation of anything. The loop, the three wire adapters, the vault
// tool set with its path jail, the thread store and the usage sink all live in `agent/` and
// know nothing about jobs, conversations, or a phone. This module is the BINDING — it turns a
// bridge [`TurnRequest`] into an `agent` `TurnInput`, hands the loop a sink that forwards into
// the job store, and turns the outcome back into what the driver expects. If a decision here
// is about how a model behaves, it is in the wrong file.
//
// WHY THE BOUNDARY IS DIFFERENT IN KIND, and this is the thing to understand before changing
// anything here. A claude-code turn is contained by a TOOL ALLOWLIST over a CLI that also has
// a shell; a codex turn by an OS SANDBOX around a process that is mostly a shell. This turn
// has no shell, no subprocess, and no MCP servers: it has eight typed tools dispatched by
// exact name, over a store that resolves every path inside a canonicalised root. The
// containment question changes shape with it — there is no argv to record, so
// [`Harness::capability_args`] records the tool MANIFEST instead, and
// `bridge/containment-direct.toml` is generated by the agent crate's own battery rather than
// by spawning children. See SECURITY.md's `direct` section for the full comparison.

/// The registry id.
pub const DIRECT_ID: &str = "direct";

/// The direct harness. A unit struct, like the other two: it is a shared registry singleton
/// serving concurrent turns, so every piece of per-process state lives in [`DirectRuntime`]
/// and every piece of per-turn state is a local in [`Direct::run`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Direct;

/// The images this harness hands a model directly.
///
/// **PNG AND JPEG, AND NO PDF** — the honest list rather than an aspirational one. The two
/// wires carry an image as base64 with a media type, and those are the two types both accept
/// from every provider tested. A PDF is not an image on either wire, so declaring it here
/// would mean handing a provider bytes it rejects at the API, on a turn the user already
/// waited for.
///
/// Saying so is what makes the EXISTING preparation path do the right thing:
/// [`prepare_attachments_for_harness`] rasterises a PDF through `cgpdf` into PNG pages before
/// the turn starts, exactly as it already does for Codex. Nothing new was written for this —
/// the declaration is the whole mechanism.
///
/// The instruction says nothing about a tool, because unlike the other two harnesses there is
/// no tool to name: the images are already IN the message the model reads, as image blocks.
/// A sentence telling it to go and open them would be an instruction to use a tool it does
/// not have.
pub static DIRECT_ATTACHMENTS: AttachmentSupport = AttachmentSupport {
    native: &["png", "jpg"],
    instruction: "they are attached to this message and you can see them directly. There is \
                  no tool to open them with and none is needed.",
};

/// The rows this harness's record must carry: one per level, with NO MCP servers at any of
/// them.
///
/// **THE MCP AXIS IS EMPTY AND ALWAYS WILL BE**, which is why there are three rows here and
/// four on each of the other two. `McpSet` describes servers a CHILD PROCESS launches; this
/// harness launches no processes at all, so the axis has exactly one value and the row label
/// is `<level>/none` for every row. A future MCP-over-stdio tool source (D10) would add tools
/// to the manifest [`Harness::capability_args`] records, not servers to this axis.
pub const DIRECT_SHIPPED_ROWS: [ContainmentRow; 3] = [
    ContainmentRow {
        capability: Capability::Basic,
        mcp: McpSet::None,
    },
    ContainmentRow {
        capability: Capability::Read,
        mcp: McpSet::None,
    },
    ContainmentRow {
        capability: Capability::Write,
        mcp: McpSet::None,
    },
];

impl Harness for Direct {
    fn id(&self) -> &'static str {
        DIRECT_ID
    }

    /// TRUE. The loop emits a text delta per streamed chunk on both wires, and
    /// [`DirectSink`] forwards each one into the same job-store frame a claude-code delta
    /// lands in. The driver's streamed-text safety net therefore covers this harness exactly
    /// as it covers claude-code.
    fn streams_text(&self) -> bool {
        true
    }

    /// TRUE AT EVERY LEVEL, and unlike the other two harnesses this is not a claim about a
    /// flag — it is a claim about what is in the manifest.
    ///
    /// `Basic` is an EMPTY tool set: the loop sends no tools at all, so there is nothing for
    /// the model to call. That is the level Codex cannot express (its shell is not an
    /// optional tool), and it is trivially expressible here because the tool set is
    /// constructed rather than configured. `Read` is the four read/lookup tools; `Write` adds
    /// the four mutators. Each is a distinct, enumerable posture — see
    /// [`Harness::capability_args`], which returns exactly those names.
    fn expresses(&self, _capability: Capability) -> bool {
        true
    }

    /// **FOUR**, and the number is chosen for a different reason from the other two.
    ///
    /// A claude-code or codex turn costs a PROCESS: a CLI startup, its MCP server subprocesses,
    /// and their memory. Three concurrent ones is already a meaningful share of the Studio.
    /// A direct turn costs an HTTP connection and a future — no fork, no exec, no server
    /// subprocesses — so the limiting resource is the provider's own rate limit rather than
    /// this machine, and the global ceiling still applies above this number either way.
    ///
    /// Four rather than something much larger because concurrency here is still not free: each
    /// turn holds a tool set over the same vault, and the write lock serialises the turns that
    /// actually write. A number chosen to look generous would only move the queue from the
    /// slot table to the broker.
    fn default_concurrency(&self) -> usize {
        4
    }

    /// TRUE — and it means what [`Harness::supports_write_lock`] says an in-process harness
    /// answering `true` must mean: locks are taken through [`crate::LockBroker`] DIRECTLY, in
    /// this process, by [`BrokerGuard`], around every write the tool set performs.
    ///
    /// There is no hook config, no helper binary and no `WriteLockChild` command string on
    /// this path — those exist to get a CHILD process to the broker, and there is no child.
    /// What there is instead is strictly stronger: the guard is called by the store, inside
    /// the same critical section as the write, on the same code path, with no process
    /// boundary in between and nothing to forget to install.
    fn supports_write_lock(&self) -> bool {
        true
    }

    /// **ALL THREE.** D8 landed the Responses adapter, and this is the line it changed.
    ///
    /// This is the one harness whose answer follows a LIBRARY rather than a CLI:
    /// `jesse_agent::provider::build_provider` now has an adapter for every wire the enum
    /// declares, so this returns `true` for every wire the enum declares. The two must
    /// agree in that direction and no other — claiming a wire the library refuses would let
    /// a model pass startup validation and then fail every turn at provider construction,
    /// which is the same healthy-then-dead shape the wire gate exists to prevent, arrived
    /// at from the library side.
    ///
    /// Still an exhaustive `match` rather than a bare `true`, and deliberately: when the
    /// next wire is DECLARED (which happens a step before its adapter exists, by design —
    /// see `jesse_agent::provider::ConfigError::UnimplementedWire`), this fails to compile
    /// and somebody has to answer for it. `true` would silently claim it.
    ///
    /// **This is also what makes `direct` the second way to reach an OpenAI-shaped model**,
    /// beside `codex`. They are not equivalent: a Codex-harness turn reaches the vault
    /// through a SHELL under an OS sandbox, a direct turn through eight typed tools with no
    /// subprocess at all. `jesse.example.toml` states which to prefer and why.
    fn supports_wire(&self, wire: Wire) -> bool {
        match wire {
            Wire::Messages | Wire::Chat | Wire::Responses => true,
        }
    }

    /// **THE TOOL MANIFEST, AS ARGV-SHAPED TOKENS** — `["--tools", "a,b,c"]`, names sorted,
    /// comma-joined, and `["--tools", ""]` at `Basic`.
    ///
    /// There is no argv. This harness spawns nothing, so the thing a containment record has
    /// to pin is not a command line but the SET OF TOOLS the model is handed — which is the
    /// whole boundary here, in the same way the flag list is the whole boundary on
    /// claude-code.
    ///
    /// **Shaped as argv anyway, deliberately.** `validate_toolset_argv` compares this to the
    /// committed record by STRICT EQUALITY and the record format stores a `toolset_args`
    /// array of strings. Inventing a second record shape for one harness would mean a second
    /// comparison, a second parser and a second way for a record to be subtly wrong; a
    /// two-token vector costs nothing and reuses machinery that is already exact. The `--tools`
    /// spelling is borrowed from claude-code's flag of the same name and means the same thing:
    /// this, and nothing else, is at the root.
    ///
    /// SORTED because the record is compared by equality and the manifest's order is the tool
    /// set builder's, which is an implementation detail nobody should be able to break the
    /// startup gate by tidying.
    ///
    /// It takes the names from `jesse_agent::tools::vault::expected_names`, the agent crate's
    /// own statement of what a level exposes, rather than listing them here — two lists would
    /// be two lists to keep in step, and the one that matters is the one the loop actually
    /// builds.
    fn capability_args(&self, _cfg: &Config, capability: Capability) -> Vec<String> {
        let mut names = expected_names(Level::from(capability));
        names.sort_unstable();
        vec!["--tools".to_string(), names.join(",")]
    }

    fn shipped_rows(&self) -> &'static [ContainmentRow] {
        &DIRECT_SHIPPED_ROWS
    }

    /// `None` — this harness writes no transcript in a directory layout the bridge scans.
    ///
    /// It keeps its threads in [`FileThreadStore`] under `<state_dir>/direct-threads/`, in the
    /// agent crate's own jsonl format, which is not the `~/.claude/projects` layout the scan
    /// reads. Answering `None` is what makes the existing rules apply unchanged: conversation
    /// ADOPTION skips it (there are no stray transcript stems to adopt — every direct thread
    /// is created by a turn the bridge already registered), the GC SWEEP skips it (a
    /// size-bounded prune of unreferenced thread files runs beside it instead), and the
    /// RESUME existence check skips it (there is no file whose absence could justify dropping
    /// a resume).
    ///
    /// **HYDRATION IS THE ONE THAT DOES NOT DEGRADE**, and that is new. D4's doc comment
    /// recorded that a transcript-less harness returns an empty turn list from
    /// `GET /jesse/conversations/{id}/transcript`, accepted deliberately. This harness has the
    /// history — it is in the thread store — so it implements [`Harness::hydrate`] and renders
    /// its own turns rather than taking that degradation. The `None` here is about the
    /// DIRECTORY SCAN, not about whether history exists.
    fn transcript_dir(&self, _cfg: &Config) -> Option<PathBuf> {
        None
    }

    /// Read the turns of one direct thread out of the thread store.
    ///
    /// See [`Harness::hydrate`] for the contract. Two rules are applied here and nowhere else:
    /// the user text is un-wrapped through [`strip_prompt_wrapper`] so the phone sees what was
    /// typed rather than the bridge's assembled prompt, and TOOL MESSAGES ARE NOT RENDERED —
    /// the phone has never shown a tool result and must not start now, on a harness whose tool
    /// results are vault content.
    fn hydrate(&self, cfg: &Config, session_id: &str) -> Option<Vec<HydratedTurn>> {
        DirectRuntime::get(cfg).ok()?.hydrate(session_id)
    }

    fn attachment_support(&self) -> &'static AttachmentSupport {
        &DIRECT_ATTACHMENTS
    }

    /// IN PROCESS: there is no child anywhere on this path.
    fn runner(&self) -> Runner<'_> {
        Runner::InProcess(self)
    }
}

// ---- The per-process runtime ------------------------------------------------

/// Everything the direct harness needs that outlives a turn: the providers, the thread store,
/// the usage sink, the vault settings, and the scope every turn acts under.
///
/// **ONE PER PROCESS, BUILT ONCE, LAZILY.** The harness itself is a unit struct in the
/// registry (like the other two, and for the same reason: it is a shared singleton serving
/// concurrent turns), and the registry is built inside [`Config::from_env`] where none of this
/// exists yet. So the runtime is a `OnceLock` initialised on the first turn from the `&Config`
/// the driver already passes in, rather than a field the registry would have to be restructured
/// to carry.
///
/// Building providers once is not an optimisation: a `reqwest::Client` owns a connection pool,
/// and one per turn would open a new TLS connection for every message the phone sends.
pub struct DirectRuntime {
    /// Model id → its provider. Only models whose token env var actually resolved appear
    /// here; an unarmed model is `configured: false` and never reaches a turn.
    providers: HashMap<String, Box<dyn Provider>>,
    threads: FileThreadStore,
    usage: JsonlUsageSink,
    /// The vault root, canonicalised once.
    vault: PathBuf,
    settings: DirectSettings,
    scope: Scope,
}

/// The `[direct]` config table, resolved.
///
/// **THE DERIVED `Default` IS THE SHIPPED POSTURE, and every field's default is the
/// conservative one on purpose:** no extra exclusions beyond the agent crate's own
/// `ALWAYS_EXCLUDED`, no cold prefixes, an EMPTY fetch allowlist (so `fetch_url` appears in
/// the manifest at `Read` and refuses every URL), the built-in grep index, and the agent
/// crate's own iteration and tool-call ceilings. A deployment that writes no `[direct]` table
/// gets a harness that can read and search its vault and reach nothing outside it.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct DirectSettings {
    /// Extra store exclusions on top of the agent crate's `ALWAYS_EXCLUDED`.
    pub exclude: Vec<String>,
    /// Path prefixes whose documents are cold: listable, unreadable, unwritable.
    pub cold_prefixes: Vec<String>,
    /// Host patterns `fetch_url` may reach. **EMPTY BY DEFAULT** — every URL refused.
    pub fetch_allow: Vec<String>,
    /// Search with `qmd` rather than the built-in grep index.
    pub qmd: bool,
    /// The qmd COLLECTION whose documents map onto the vault root.
    ///
    /// Required when `qmd` is set and deliberately not guessed: `qmd` reports a hit as
    /// `qmd://<collection>/<path>`, and stripping the wrong prefix produces ids that resolve
    /// to the wrong documents or to none. On this machine the collection covering the vault
    /// is not named after it, which is exactly why a default would be wrong.
    pub qmd_collection: Option<String>,
    /// Per-turn ceilings, overriding the agent crate's defaults. `None` keeps the default.
    pub max_iterations: Option<u32>,
    pub max_tool_calls: Option<u32>,
}

/// The broker this process's direct turns take their write locks through.
///
/// Installed by [`AppState::new`], which is the first place both the broker and the harness
/// registry exist. A `OnceLock` rather than a field because the registry is built from
/// `Config` and the broker is not part of `Config` — threading it through would mean the
/// config layer knowing about a runtime service it has no other use for.
///
/// **UNSET MEANS WRITES ARE REFUSED, never writes without a lock.** A direct turn in a process
/// that never installed a broker (a unit test, a one-shot) still reads and searches; a write
/// gets [`GuardRefused::Unavailable`], whose documented meaning is exactly this case — the
/// situation where another writer is unaccounted for. See [`BrokerGuard`].
static DIRECT_BROKER: std::sync::OnceLock<Arc<LockBroker>> = std::sync::OnceLock::new();

/// Give this process's direct turns their write-lock broker. Idempotent; the first call wins.
pub fn install_direct_broker(broker: Arc<LockBroker>) {
    let _ = DIRECT_BROKER.set(broker);
}

static DIRECT_RUNTIME: std::sync::OnceLock<Result<DirectRuntime, String>> =
    std::sync::OnceLock::new();

impl DirectRuntime {
    /// The process's runtime, building it on first use.
    ///
    /// The `Result` is CACHED, including the failure. A runtime that could not be built (an
    /// unreadable state dir, a vault root that does not resolve) will not build on the next
    /// turn either, and retrying it per turn would turn one startup problem into a stream of
    /// identical per-turn errors with a filesystem call each.
    pub fn get(cfg: &Config) -> Result<&'static DirectRuntime, String> {
        DIRECT_RUNTIME
            .get_or_init(|| DirectRuntime::build(cfg))
            .as_ref()
            .map_err(|e| e.clone())
    }

    fn build(cfg: &Config) -> Result<DirectRuntime, String> {
        let state = cfg
            .state_dir
            .as_deref()
            .ok_or_else(|| {
                "the direct harness needs a state directory (JESSE_STATE_DIR) for its thread \
                 store and usage log"
                    .to_string()
            })
            .map(PathBuf::from)?;
        let threads = FileThreadStore::open(state.join(DIRECT_THREADS_DIR))
            .map_err(|e| format!("direct thread store: {e}"))?;
        let usage = JsonlUsageSink::open(state.join(USAGE_FILE))
            .map_err(|e| format!("direct usage log: {e}"))?;
        let vault = std::fs::canonicalize(&cfg.vault)
            .map_err(|e| format!("vault root {}: {e}", cfg.vault))?;
        let settings = cfg.direct.clone();

        let mut providers = HashMap::new();
        for m in &cfg.model_registry.models {
            if m.harness != DIRECT_ID || !m.configured {
                continue;
            }
            let Some((base_url, token, model)) = m.backend.as_ref() else {
                continue;
            };
            let pc = provider_config_for(m, base_url, token, model);
            match build_provider(pc) {
                Ok(p) => {
                    providers.insert(m.id.clone(), p);
                }
                // Named, never silent: a model the startup gate let through whose provider
                // will not construct is a wiring fault an operator has to be able to see.
                Err(e) => eprintln!(
                    "jesse-bridge: direct model '{}' has no usable provider ({e}); its turns \
                     will fail until the wire or base_url is corrected.",
                    m.id
                ),
            }
        }

        Ok(DirectRuntime {
            providers,
            threads,
            usage,
            vault,
            settings,
            // THE SINGLE-TENANT BINDING, constructed once. Phase 2 replaces this with a real
            // tenant/user/workspace triple resolved per request; until then every turn on this
            // deployment acts for the one owner the persona names, in the one vault
            // `JESSE_VAULT` points at. It is a fixed value rather than an absent one because
            // every store and tool method takes a scope: passing a real, honest, constant
            // scope is what lets the Phase 2 implementation key on it without a signature
            // change anywhere.
            scope: Scope::new("local", persona_user_slug(&cfg.persona), "vault"),
        })
    }

    /// Render one direct thread as the phone's transcript. See [`Direct::hydrate`].
    fn hydrate(&self, session_id: &str) -> Option<Vec<HydratedTurn>> {
        use jesse_agent::provider::Role;
        use jesse_agent::thread::ThreadStore;
        let id = ThreadId::parse(session_id).ok()?;
        let thread = self.threads.load(&id).ok()?;
        let mut out = Vec::new();
        for (i, msg) in thread.messages.iter().enumerate() {
            // TOOL RESULTS ARE NOT RENDERED. A `ToolResult` block carries vault content the
            // phone has never been shown, and a `ToolUse` block carries the model's arguments;
            // both are deliberately outside the mid-turn contract and neither belongs in a
            // transcript either. Only the visible text of a message survives.
            let text: String = msg
                .content
                .iter()
                .filter_map(|b| match b {
                    ContentBlock::Text(t) => Some(t.as_str()),
                    _ => None,
                })
                .collect::<Vec<_>>()
                .join("");
            if text.trim().is_empty() {
                continue;
            }
            let (role, text) = match msg.role {
                // The stored user message is the bridge's assembled prompt — clock line,
                // device blocks, catch-up, floor, wrapper. The phone must see what was typed.
                Role::User => ("user", strip_prompt_wrapper(&text)),
                Role::Assistant => ("assistant", text),
            };
            if text.trim().is_empty() {
                continue;
            }
            out.push(HydratedTurn {
                role: role.to_string(),
                text,
                timestamp: None,
                // The same stable shape the transcript path uses (`<session>:<offset>`), with
                // the message INDEX standing in for the byte offset: the thread log is
                // append-only, so an index is stable for the life of the thread and unique
                // within it, which is exactly what a client merging history needs.
                turn_key: Some(format!("{session_id}:{i}")),
                artifacts: Vec::new(),
            });
        }
        Some(out)
    }
}

/// `<state_dir>/direct-threads/` — where [`FileThreadStore`] keeps this harness's threads.
pub const DIRECT_THREADS_DIR: &str = "direct-threads";
/// `<state_dir>/usage.jsonl` — one record per PROVIDER CALL. See [`JsonlUsageSink`].
pub const USAGE_FILE: &str = "usage.jsonl";
/// How long a usage record is kept before the startup prune drops it.
pub const USAGE_RETENTION_DAYS: u64 = 90;

/// The owner's name as a scope-safe user id.
///
/// Lowercase, non-alphanumerics collapsed to `-`. It is an IDENTIFIER in a usage record, not a
/// display name: the record is content-free and this is the only field that could carry a
/// person's name into it, so it is deliberately the persona's already-configured owner name
/// rather than anything read from the system.
fn persona_user_slug(persona: &Persona) -> String {
    let s: String = persona
        .owner_name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    let s = s.trim_matches('-').to_string();
    if s.is_empty() {
        "owner".to_string()
    } else {
        s
    }
}

// ---- Provider construction --------------------------------------------------

/// Build one model's [`ProviderConfig`] from its registry entry.
///
/// Everything here comes from config the operator already writes for every other harness —
/// the same `base_url` / `auth_token_env` / `model` triple, the same `wire`, the same
/// `health.timeout_secs`. Nothing about a direct model is configured in a new place; the
/// harness key is the only thing that changes.
///
/// **THE AUTH SCHEME IS RESOLVED, NOT GUESSED AT CALL TIME.** `AuthScheme::default_for` picks
/// `x-api-key` for `api.anthropic.com` and bearer everywhere else, on the HOST rather than a
/// substring — so a gateway at `https://gw/proxy/api.anthropic.com` is not mistaken for the
/// real thing. An explicit `auth_scheme` key wins, because a gateway that wants the other
/// header is a real deployment and no host test can know that.
///
/// **THE CONNECT TIMEOUT TAKES `health.timeout_secs` AS A FLOOR.** A model an operator has
/// already told the bridge is slow to answer its probe (a reasoning model gets 15 s) should not
/// then be given the library's short connect budget: the same slowness that made them widen
/// the probe applies to the turn's first byte. It is a FLOOR rather than an assignment, so a
/// deployment that narrowed the probe budget cannot accidentally narrow the turn's.
fn provider_config_for(
    m: &RegistryModel,
    base_url: &str,
    token: &str,
    model: &str,
) -> ProviderConfig {
    let auth = match m.auth_scheme {
        Some(DirectAuthScheme::Bearer) => AuthScheme::Bearer(token.to_string()),
        Some(DirectAuthScheme::XApiKey) => AuthScheme::XApiKey(token.to_string()),
        None => AuthScheme::default_for(base_url, token),
    };
    let mut pc = ProviderConfig::new(agent_wire(m.wire), base_url, model, auth);
    // The per-host defaults `ProviderConfig::new` chose stand unless the operator overrode a
    // flag; each override is applied on its own so setting one does not reset the other two.
    if let Some(q) = m.quirks.reasoning_effort_supported {
        pc.quirks.reasoning_effort_supported = q;
    }
    if let Some(q) = m.quirks.multiple_system_messages {
        pc.quirks.multiple_system_messages = q;
    }
    if let Some(q) = m.quirks.strict_tools {
        pc.quirks.strict_tools_supported = q;
    }
    let floor = Duration::from_secs(m.health.timeout_secs.max(1));
    if pc.timeouts.connect < floor {
        pc.timeouts.connect = floor;
    }
    if pc.timeouts.overall < floor {
        pc.timeouts.overall = floor;
    }
    pc
}

/// The bridge's wire, as the agent crate's.
///
/// A fourth conversion that would live in [`crate::agentmap`] if it were needed anywhere else;
/// it is needed only here, so it is here. Every arm is now reachable: since D8 this harness
/// answers `supports_wire` yes for all three, so all three arrive here on a real turn.
fn agent_wire(w: Wire) -> AgentWire {
    match w {
        Wire::Messages => AgentWire::Messages,
        Wire::Chat => AgentWire::Chat,
        Wire::Responses => AgentWire::Responses,
    }
}

// ---- The write guard, over the bridge's broker -------------------------------

/// The agent crate's [`WriteGuard`], implemented over [`crate::LockBroker`].
///
/// **THIS IS WHAT `supports_write_lock() == true` MEANS FOR AN IN-PROCESS HARNESS.** The other
/// two harnesses reach the broker by writing a hook config that makes their child shell out to
/// `jesse-hook`, which opens a unix socket and asks. There is no child here, so the guard calls
/// the broker directly — same broker, same lock table, same keys, same wait timeout. A
/// claude-code turn and a direct turn writing the same file contend for the same lock, which is
/// the only property that matters.
///
/// ## Where the compare-and-swap lives, and why the other one was removed
///
/// There were two candidates and running both would have meant two refusals for one condition.
///
/// **THE STORE HOLDS IT.** `vault_read` hands the model a content hash and `vault_write` /
/// `vault_edit` demand it back; `FsVaultStore` re-reads the file UNDER THE LOCK and refuses on
/// a mismatch. The broker's own per-conversation baseline check (`check_baseline`, which the
/// `Pre` hook runs) is deliberately NOT invoked on this path.
///
/// Three reasons, in order of weight:
///
///   1. **The store's check is inside the same critical section as the write**, in the same
///      code path, with no process boundary in between. The broker's runs in a hook that, for
///      a CLI child, is a separate short-lived process whose answer is already advisory by the
///      time the child actually writes. That is sound enough where it is the only option
///      available; it is strictly weaker than checking in the code that does the writing, and
///      here we have the choice.
///   2. **The store's baseline is the one the model is actually holding.** It covers exactly
///      "the bytes I decided this edit against". The broker's covers "the last bytes anyone in
///      this conversation saw", which across a multi-tool-call turn can be an older read of a
///      different file version — so the two do not even always agree about what a conflict is.
///   3. Two enforcement points mean two refusal messages for one condition, one of them phrased
///      for a CLI child ("Re-read the file and redo this edit"), reaching a model that reads
///      tool errors as instructions.
///
/// **The baseline is still FED, and that is not the same as enforcing it.** `note_read` records
/// what a direct turn read, and [`BrokerGuard::release`] re-records the file after a write —
/// exactly what the `Post` hook does for a child. Neither is consulted for a direct write. They
/// exist because a conversation can be served by a DIFFERENT harness on a later turn (the model
/// chip is per conversation and the user may move it), and a claude-code turn that follows a
/// direct one must not be blind to what the direct turn read, nor be falsely refused because
/// the direct turn's write left the broker's baseline stale.
pub struct BrokerGuard {
    /// `None` when no broker was installed — see [`DIRECT_BROKER`]. Writes are then REFUSED.
    broker: Option<Arc<LockBroker>>,
}

impl BrokerGuard {
    fn new() -> Self {
        BrokerGuard {
            broker: DIRECT_BROKER.get().cloned(),
        }
    }
}

impl WriteGuard for BrokerGuard {
    fn acquire<'a>(
        &'a self,
        path: &'a Path,
        turn: &'a str,
        // UNUSED, and that is the compare-and-swap decision showing through. The broker keys
        // LOCKS on (turn, call) and BASELINES on conversation; this method takes only a lock,
        // so the conversation is not part of the key. It is `note_read` and `release` that
        // touch the baseline, and both have it.
        _conversation: &'a str,
        call_id: &'a str,
    ) -> Pin<Box<dyn Future<Output = Result<GuardPermit, GuardRefused>> + Send + 'a>> {
        Box::pin(async move {
            let Some(broker) = self.broker.as_ref() else {
                // The fail-safe. `Unavailable` is documented as covering exactly this: the case
                // where another writer is unaccounted for. Refusing is the only answer that
                // cannot corrupt the vault.
                return Err(GuardRefused::Unavailable(
                    "this process has no write-lock broker installed".to_string(),
                ));
            };
            let started = Instant::now();
            // THE LOCK ONLY — no baseline check. See the type's doc comment for where the
            // compare-and-swap lives and why it is not here.
            //
            // The git lock is taken with it, on the same reasoning the hook path takes it: a
            // write can trigger a vault hook that runs git, so a write-lock holder holds the
            // git lock too, taken inside the file lock to match the one total order.
            if broker
                .acquire_direct(&LockKey::Path(path.to_path_buf()), turn, call_id)
                .await
                && broker.acquire_direct(&LockKey::Git, turn, call_id).await
            {
                return Ok(GuardPermit {
                    path: path.to_path_buf(),
                    // The call id IS the handle: `release_call` is keyed on (turn, call), which
                    // is what the broker already uses for the hook path.
                    token: format!("{turn}\u{1f}{call_id}"),
                });
            }
            broker.release_call_direct(turn, call_id);
            Err(GuardRefused::Busy {
                path: path.to_path_buf(),
                waited_ms: started.elapsed().as_millis() as u64,
            })
        })
    }

    fn release(&self, permit: GuardPermit) {
        let Some(broker) = self.broker.as_ref() else {
            return;
        };
        let Some((turn, call_id)) = permit.token.split_once('\u{1f}') else {
            return;
        };
        // Re-record the file's bytes as this conversation's baseline BEFORE releasing, exactly
        // as the `Post` hook does — see the type's doc comment. A write that left the broker's
        // baseline stale would falsely refuse the next claude-code turn in this conversation.
        broker.record_baseline_direct(&permit.path);
        broker.release_call_direct(turn, call_id);
    }

    fn note_read(&self, conversation: &str, path: &Path, hash: &ContentHash) {
        let Some(broker) = self.broker.as_ref() else {
            return;
        };
        broker.note_direct_read(conversation, path, hash.as_str());
    }
}

// ---- The sink ---------------------------------------------------------------

/// The agent loop's [`EventSink`], forwarding into the bridge's [`TurnSink`].
///
/// Two events in, the same two events out, and nothing translated: the agent crate's
/// `ToolActivity { name, refused }` and the bridge's carry the same two fields with the same
/// meanings, because D2 wrote the loop's vocabulary to match the mid-turn contract at the top
/// of `harness/mod.rs` rather than inventing a second one.
///
/// The one thing this type is careful about is what it does NOT forward. `ToolError::Refused`
/// becomes the `refused` bit; a tool's RESULT, its ARGUMENTS and its timing do not appear here
/// at all, because the contract says they never reach a phone screen.
struct DirectSink<'a> {
    inner: &'a dyn TurnSink,
    /// Whether visible text may be streamed at all.
    ///
    /// FALSE UNDER [`StylePolicy::Regenerate`], and it is a correctness fix rather than a
    /// preference. The mid-turn contract says everything sent as a delta must also appear in
    /// the final [`TurnOutcome::text`] and must never be sent twice; a regenerated turn
    /// DISCARDS the text it streamed and delivers a different answer, which breaks the first
    /// half of that. So a deployment that has asked for rewrites gets the answer whole, at the
    /// end, instead of watching one answer arrive and a different one replace it. Every other
    /// policy streams exactly as before.
    stream_text: bool,
}

impl EventSink for DirectSink<'_> {
    fn on_text_delta(&self, delta: &str) {
        if !self.stream_text {
            return;
        }
        self.inner.text_delta(delta);
    }

    fn on_tool_activity(&self, activity: jesse_agent::ToolActivity) {
        self.inner.tool_activity(ToolActivity {
            name: activity.name,
            refused: activity.refused,
        });
    }
}

